// GPLTStyleHint returns Chinese prose style-guidance injected into the
// statement prompt for 团体程序设计天梯赛 problems. The guidance covers
// structure, scoring convention, and tier-specific knowledge range so the LLM
// produces statements that match real PAT-GPLT problems.
func GPLTStyleHint(tier domain.GPLTTier) string {
	base := `题面必须采用中文，并严格遵循 团体程序设计天梯赛（PAT-GPLT）典型格式：
- 标准结构：## 题目描述 / ## 输入格式 / ## 输出格式 / ## 样例 / ## 数据范围与约定
- 题面描述风格偏向叙事（可适度有背景故事），但变量定义、输入输出格式、边界条件必须严谨无歧义。
- 样例至少给出 1 组，并配 ## 样例说明 解释关键思路或边界。
- ## 数据范围与约定 中用分组列出不同数据规模及对应分值，形如：
    - 对 30% 的数据：n ≤ 100（6 分）
    - 对 70% 的数据：n ≤ 10^5（额外 7 分）
    - 对 100% 的数据：n ≤ 10^6（满分）
- 一行 hint 使用简洁中文，给出核心算法方向而不剧透完整解法。

【核心侧重点：代码实现】
天梯赛考查的是"能不能把想法准确写成代码"，而不是证明定理或推导公式：
- 优先选择"思路一眼看出、但需要细心处理边界/格式/数据结构操作"的题。
- 避免需要大量数学推导、证明、建模抽象才能入手的题目。
- 题面描述应让选手**读完后马上知道要干什么**，主要时间花在写代码、调试细节上。
- 数据范围服务于实现正确性，而不是逼选手寻找更优的时间复杂度下界。
`
	switch tier {
	case domain.GPLTTierL1:
		return base + `L1 层级要求（天梯赛 L1 真实分值为 5/5/10/10/15/15/20/20，本题分值以 ## 数据范围与约定 中的总分为准）：
- 只考查最基础的编程能力：输入输出、循环、条件、数组、字符串、简单数学、简单模拟。
- 不得出现任何需要"算法思维"的题（不要 DP / 图论 / 复杂数据结构 / 贪心证明等核心考点）。
- 5 分题：最基础的 I/O + 简单运算，n ≤ 100~1000。
- 10 分题：带循环+条件的一点点处理，n ≤ 10^4。
- 15 分题：多步骤模拟或较复杂的字符串/数组操作，n ≤ 10^5。
- 20 分题：稍带思维的综合模拟题（可��需要排序、前缀和等入门技巧），n ≤ 10^5。
- 推荐时间复杂度 O(n) 或 O(n log n) 足够。
- 预期完成时间：5–15 分钟。`
	case domain.GPLTTierL2:
		return base + `L2 层级要求（总分 25，侧重代码实现）：
- 与 L1 的区别**不是"更难写"**，而是"**必须用上特定的数据结构或算法**"：栈/队列/链表/二叉树的基本操作、并查集、图的 BFS/DFS/最短路入门、基础 DP（线性/背包）、二分、贪心。
- 很多 L2 题目的代码量甚至比 20 分的 L1 模拟题还要少，重点是选手能识别"这里要用 XX"并正确写出来。
- 避免需要复杂建模或数学推导才能入手的题目；数据结构和算法应**在题面中被自然地引导出来**，而不是让选手猜。
- 题面要明确指向某个知识点，数据规模 10^3 ~ 10^6，能卡掉 O(n^2) 暴力但不要求复杂优化。
- 预期完成时间：15–30 分钟，其中大部分时间用在**写代码和调试**上。`
	case domain.GPLTTierL3:
		return base + `L3 层级要求（总分 30，侧重代码实现复杂度）：
- 综合考查：复杂 DP（区间/树形/状压/数位）、图论进阶（最小生成树、拓扑+DP、二分图匹配）、数据结构进阶（线段树、树状数组）、字符串（KMP/哈希）、组合与数论常用技巧。
- L3 的难度主要来自"**把较复杂的算法正确实现出来**"——代码量大、细节多、边界繁琐。
- 题面仍应让选手较快看出该用哪类算法，而不是依赖奇巧的数学观察或长篇推导。关键技巧应是算法模板或经典套路的组合使用。
- 数据规模 10^5 ~ 10^6，卡掉 O(n^2) 等低效解法，但不要求选手发明新算法。
- 预期完成时间：30–60 分钟，其中主要时间用在**写代码、对拍、处理边界**上。`
	}
	return base
}

